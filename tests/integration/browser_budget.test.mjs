test('private ledger persists reservations, bounds concurrency and preserves estimates', async t => {
  const dir = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'captcha-budget-')));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const limits = { estimate: 3000, dailyTasks: 1, lifetimeTasks: 1, dailyMicros: 3000, lifetimeMicros: 3000 };
  assert.equal(await reserveBudget(dir, { ...limits, id: 'a'.repeat(64) }), false);
  await initializeBudget(dir);
  const results = await Promise.all(['a', 'b'].map(x => reserveBudget(dir, { ...limits, id: x.repeat(64) })));
  assert.deepEqual(results.sort(), [false, true]);
  const data = JSON.parse(fs.readFileSync(path.join(dir, 'captcha-budget.json')));
  assert.equal(data.entries.length, 1);
  assert.equal(await settleBudget(dir, data.entries[0].id, 1000), true);
  assert.equal(await settleBudget(dir, data.entries[0].id, 1000), true);
  assert.equal(await settleBudget(dir, data.entries[0].id, 1001), false);
  assert.equal(await reserveBudget(dir, { ...limits, id: 'c'.repeat(64) }), false);
  await assert.rejects(initializeBudget(dir));
  fs.chmodSync(path.join(dir, 'captcha-budget.json'), 0o644);
  assert.equal(await reserveBudget(dir, { ...limits, id: 'd'.repeat(64) }), false);
  fs.chmodSync(path.join(dir, 'captcha-budget.json'), 0o600);
  const next = path.join(dir, 'next'); fs.mkdirSync(next, { mode: 0o700 }); await initializeBudget(next);
  const wider = { ...limits, dailyTasks: 3, lifetimeTasks: 3, dailyMicros: 6000, lifetimeMicros: 6000 };
  assert.equal(await reserveBudget(next, { ...wider, id: 'e'.repeat(64) }), true);
  assert.equal(await settleBudget(next, 'e'.repeat(64), 4500), true);
  assert.equal(await reserveBudget(next, { ...wider, id: 'f'.repeat(64) }), false);
  fs.writeFileSync(path.join(next, 'captcha-budget.json'), '{broken');
  assert.equal(await reserveBudget(next, { ...wider, id: 'f'.repeat(64) }), false);
});

test('unresolved receipt is a durable global barrier until trustworthy reconciliation', async t => {
  const dir = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'captcha-barrier-')));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  await initializeBudget(dir);
  const limits = { estimate: 3000, dailyTasks: 10, lifetimeTasks: 10, dailyMicros: 30000, lifetimeMicros: 30000 };
  const candidates = ['a', 'b', 'c', 'd', 'e', 'f'];
  const worker = `const { reserveBudget } = await import(process.argv[1]); console.log(JSON.stringify(await reserveBudget(process.argv[2], JSON.parse(process.argv[3]))));`;
  const moduleUrl = fileURLToPath(new URL('../../scripts/opencode-browser-budget.mjs', import.meta.url));
  const winners = await Promise.all(candidates.map(async x => {
    const { stdout } = await promisify(execFile)(process.execPath, ['--input-type=module', '-e', worker, moduleUrl, dir, JSON.stringify({ ...limits, id: x.repeat(64) })]);
    return JSON.parse(stdout);
  }));
  assert.equal(winners.filter(Boolean).length, 1);
  const entry = JSON.parse(fs.readFileSync(path.join(dir, 'captcha-budget.json'))).entries[0];
  assert.equal(entry.actual, null);
  assert.equal(await reserveBudget(dir, { ...limits, id: 'f'.repeat(64) }), false);
  const cli = fileURLToPath(new URL('../../scripts/browser-budget.mjs', import.meta.url));
  assert.match(execFileSync(process.execPath, [cli, 'reconcile', dir, entry.id, '2000'], { encoding: 'utf8' }), /Receipt recorded/);
  const nextId = '9'.repeat(64);
  assert.equal(await reserveBudget(dir, { ...limits, id: nextId }), true);
  assert.equal(await settleBudget(dir, nextId, 50000), true);
  assert.equal(await reserveBudget(dir, { ...limits, id: '8'.repeat(64) }), false);
});

test('production MCP solves through actual Chromium and loopback provider with persistent reservation and redaction', { timeout: 30000 }, async t => {
  const dir = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'captcha-mcp-')));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const key = path.join(dir, '.env'); fs.writeFileSync(key, 'TWOCAPTCHA_API_KEY="fixture-private-key" # fixture\n', { mode: 0o600 });
  execFileSync('openssl', ['req', '-x509', '-newkey', 'rsa:2048', '-nodes', '-keyout', path.join(dir, 'tls-key'), '-out', path.join(dir, 'cert'), '-days', '1', '-subj', '/CN=localhost'], { stdio: 'ignore' });
  let navigateNow = false, holdPoll = false, holdReceipt = false, notifyPoll, heldReceipt;
  const site = https.createServer({ key: fs.readFileSync(path.join(dir, 'tls-key')), cert: fs.readFileSync(path.join(dir, 'cert')) }, (req, res) => {
    if (req.url === '/fixture-signal') return res.end(navigateNow ? 'yes' : 'no');
    res.writeHead(200, { 'content-type': 'text/html' });
    res.end(`<title>Fixture</title><div class="cf-turnstile" style="width:200px;height:60px" data-sitekey="fixture-private-sitekey" data-callback="fixtureCallback"></div><div id="accepted" hidden>accepted</div><script>window.fixtureCallback = token => { console.log(token); document.querySelector('#accepted').textContent = token; document.querySelector('#accepted').hidden = false; }; if(location.pathname==='/navigate') setInterval(async()=>{if(await (await fetch('/fixture-signal')).text()==='yes') location.assign('/after-nav');},20);</script>`);
  });
  await new Promise(r => site.listen(0, '127.0.0.1', r));
  t.after(() => { site.closeAllConnections(); site.close(); });
  let creates = 0, ledgerAtCreate, budgetDirectory = dir, dropCreate = false;
  const provider = http.createServer((req, res) => {
    let body = ''; req.on('data', x => body += x); req.on('end', () => {
      assert.equal(JSON.parse(body).clientKey, 'fixture-private-key');
      if (req.url === '/createTask') { creates++; ledgerAtCreate = JSON.parse(fs.readFileSync(path.join(budgetDirectory, 'captcha-budget.json'))); if (dropCreate) { req.socket.destroy(); return; } return res.end(JSON.stringify({ errorId: 0, taskId: 123 })); }
      if (holdPoll) { navigateNow = true; return; }
      if (holdReceipt) { heldReceipt = res; notifyPoll(); return; }
      res.end(JSON.stringify({ errorId: 0, status: 'ready', cost: '0.002', solution: { token: 'fixture-private-token' } }));
    });
  });
  await new Promise(r => provider.listen(0, '127.0.0.1', r));
  t.after(() => { provider.closeAllConnections(); provider.close(); });
  const origin = `https://127.0.0.1:${site.address().port}`;
  await initializeBudget(dir);
  const config = { channel: 'default', captcha: { enabled: true, provider: '2captcha', timeoutMs: 5000, pollIntervalMs: 5, policy: { ledgerDir: dir, sites: [{ origin, acceptSelector: '#accepted' }], estimateMicros: 3000, dailyTasks: 1, lifetimeTasks: 1, dailyMicros: 3000, lifetimeMicros: 3000 } } };
  fs.writeFileSync(path.join(dir, 'prometheus-browser.json'), JSON.stringify(config), { mode: 0o600 });
  const env = { PROMETHEUS_CONFIG_DIR: dir, CAPTCHA_FIXTURE_PORT: String(provider.address().port), NODE_OPTIONS: `--import=${path.join(import.meta.dirname, 'captcha_fixture_preload.mjs')}` };
  const installRoot = path.join(dir, 'install'); fs.mkdirSync(installRoot, { mode: 0o700 });
  profile('install', { root: installRoot, quiescent: true, prepare(stage) { fs.symlinkSync(path.resolve(import.meta.dirname, '../../node_modules'), path.join(stage, 'node_modules')); }, verify() {} });
  const server = path.join(installRoot, 'prometheus-browser', 'opencode-playwright-mcp.mjs');
  assert.equal(fs.existsSync(path.join(path.dirname(server), '.env')), false);
  const clientOptions = { captureStderr: true, server, cwd: dir };
  const c = spawnMcpClient(env, clientOptions);
  t.after(async () => { await c.close().catch(() => {}); });
  const other = spawnMcpClient(env, clientOptions);
  t.after(async () => { await other.close().catch(() => {}); });
  const call = async (name, args) => c.textOf(await c.call(name, args));
  const callOther = async (name, args) => other.textOf(await other.call(name, args));
  await Promise.all([call('browser_navigate', { url: origin + '/' }), callOther('browser_navigate', { url: origin + '/' })]);
  const authorization = { authorize_paid: true, max_cost_usd: 0.003, max_tasks: 1 };
  const results = await Promise.all([call('browser_challenge_solve', authorization), callOther('browser_challenge_solve', authorization)]);
  assert.equal(results.filter(r => JSON.parse(r).status === 'verified').length, 1, JSON.stringify(results));
  const result = results.find(r => JSON.parse(r).status === 'verified');
  const winner = JSON.parse(results[0]).status === 'verified' ? call : callOther;
  assert.equal(creates, 1); assert.equal(ledgerAtCreate.entries.length, 1); assert.equal(ledgerAtCreate.entries[0].actual, null);
  const ledger = JSON.parse(fs.readFileSync(path.join(dir, 'captcha-budget.json')));
  assert.equal(ledger.entries[0].actual, 2000);
  for (const output of [result, await winner('browser_console_messages'), await winner('browser_snapshot'), await winner('browser_evaluate', { expression: "document.querySelector('#accepted').textContent" })]) assert.doesNotMatch(output, /fixture-private-token|fixture-private-key|fixture-private-sitekey/);
  const second = await call('browser_challenge_solve', authorization);
  assert.notEqual(JSON.parse(second).status, 'verified'); assert.equal(creates, 1);
  const restarted = spawnMcpClient(env, clientOptions);
  t.after(async () => { await restarted.close().catch(() => {}); });
  await restarted.call('browser_navigate', { url: origin + '/' });
  const afterRestart = JSON.parse(restarted.textOf(await restarted.call('browser_challenge_solve', authorization)));
  assert.notEqual(afterRestart.status, 'verified'); assert.equal(creates, 1);
  // An accepted create with a lost reply consumes the same durable slot after
  // a completely new MCP process, rather than being retried as if free.
  budgetDirectory = path.join(dir, 'ambiguous'); fs.mkdirSync(budgetDirectory, { mode: 0o700 });
  await initializeBudget(budgetDirectory);
  const ambiguousConfig = { ...config, captcha: { ...config.captcha, policy: { ...config.captcha.policy, ledgerDir: budgetDirectory } } };
  fs.writeFileSync(path.join(budgetDirectory, 'prometheus-browser.json'), JSON.stringify(ambiguousConfig), { mode: 0o600 });
  const ambiguousEnv = { ...env, PROMETHEUS_CONFIG_DIR: budgetDirectory };
  const first = spawnMcpClient(ambiguousEnv, clientOptions);
  t.after(async () => { await first.close().catch(() => {}); });
  dropCreate = true;
  await first.call('browser_navigate', { url: origin + '/ambiguous' });
  const uncertain = JSON.parse(first.textOf(await first.call('browser_challenge_solve', authorization)));
  assert.equal(uncertain.outcome, 'unknown'); assert.equal(creates, 2);
  assert.equal(JSON.parse(fs.readFileSync(path.join(budgetDirectory, 'captcha-budget.json'))).entries[0].actual, null);
  dropCreate = false;
  const retried = spawnMcpClient(ambiguousEnv, clientOptions);
  t.after(async () => { await retried.close().catch(() => {}); });
  await retried.call('browser_navigate', { url: origin + '/ambiguous' });
  const noRetry = JSON.parse(retried.textOf(await retried.call('browser_challenge_solve', authorization)));
  assert.notEqual(noRetry.status, 'verified'); assert.equal(creates, 2);
  budgetDirectory = path.join(dir, 'navigation'); fs.mkdirSync(budgetDirectory, { mode: 0o700 });
  await initializeBudget(budgetDirectory);
  const navConfig = { ...config, captcha: { ...config.captcha, policy: { ...config.captcha.policy, ledgerDir: budgetDirectory } } };
  fs.writeFileSync(path.join(budgetDirectory, 'prometheus-browser.json'), JSON.stringify(navConfig), { mode: 0o600 });
  const navigation = spawnMcpClient({ ...env, PROMETHEUS_CONFIG_DIR: budgetDirectory }, clientOptions);
  t.after(async () => { await navigation.close().catch(() => {}); });
  holdPoll = true;
  await navigation.call('browser_navigate', { url: origin + '/navigate' });
  const stale = JSON.parse(navigation.textOf(await navigation.call('browser_challenge_solve', authorization)));
  assert.equal(stale.status, 'unverified'); assert.ok(['unknown', 'submitted'].includes(stale.outcome));
  assert.equal(creates, 3);
  assert.equal(JSON.parse(fs.readFileSync(path.join(budgetDirectory, 'captcha-budget.json'))).entries[0].actual, null);
  assert.equal(navigation.textOf(await navigation.call('browser_evaluate', { expression: "document.querySelector('#accepted').hidden" })), 'true');
  holdPoll = false; navigateNow = false;
  budgetDirectory = path.join(dir, 'receipt-failure'); fs.mkdirSync(budgetDirectory, { mode: 0o700 });
  await initializeBudget(budgetDirectory);
  const failurePolicy = { ...config.captcha.policy, ledgerDir: budgetDirectory, dailyTasks: 3, lifetimeTasks: 3, dailyMicros: 6000, lifetimeMicros: 6000 };
  const failureConfig = { ...config, captcha: { ...config.captcha, policy: failurePolicy } };
  fs.writeFileSync(path.join(budgetDirectory, 'prometheus-browser.json'), JSON.stringify(failureConfig), { mode: 0o600 });
  const failureEnv = { ...env, PROMETHEUS_CONFIG_DIR: budgetDirectory };
  const failure = spawnMcpClient(failureEnv, clientOptions);
  t.after(async () => { await failure.close().catch(() => {}); });
  await failure.call('browser_navigate', { url: origin + '/receipt-failure' });
  holdReceipt = true;
  const polled = new Promise(resolve => { notifyPoll = resolve; });
  const solveFailure = failure.call('browser_challenge_solve', authorization);
  await polled;
  let entered, release;
  const locked = new Promise(resolve => { entered = resolve; });
  const unlocked = new Promise(resolve => { release = resolve; });
  const holder = withRegistryLock(budgetDirectory, async () => { entered(); await unlocked; });
  await locked;
  heldReceipt.end(JSON.stringify({ errorId: 0, status: 'ready', cost: '0.020', solution: { token: 'fixture-private-token' } }));
  let failed;
  try { failed = JSON.parse(failure.textOf(await solveFailure)); }
  finally { release(); await holder; }
  assert.notEqual(failed.status, 'verified'); assert.equal(failed.outcome, 'submitted');
  const unresolved = JSON.parse(fs.readFileSync(path.join(budgetDirectory, 'captcha-budget.json'))).entries[0];
  assert.equal(unresolved.actual, null); assert.equal(creates, 4);
  await failure.close(); holdReceipt = false;
  const afterFailure = spawnMcpClient(failureEnv, clientOptions);
  t.after(async () => { await afterFailure.close().catch(() => {}); });
  await afterFailure.call('browser_navigate', { url: origin + '/different-after-restart' });
  const blocked = JSON.parse(afterFailure.textOf(await afterFailure.call('browser_challenge_solve', authorization)));
  assert.notEqual(blocked.status, 'verified'); assert.equal(creates, 4);
  assert.equal(await settleBudget(budgetDirectory, unresolved.id, 20000), true);
  await afterFailure.call('browser_navigate', { url: origin + '/after-reconcile' });
  await afterFailure.call('browser_challenge_solve', authorization);
  assert.equal(creates, 4, 'actual overrun must remain blocking after reconciliation');
});
