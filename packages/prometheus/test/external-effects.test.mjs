import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { effectDestination } from '../qualification/effects.mjs';
import { sandboxAvailable } from '../src/sandbox.mjs';
import { startFixture } from './helpers.mjs';

for (const response of ['disconnect', 'hold']) test(`a real controlled destination retains an unknown effect after ${response}`, { timeout: 15000, skip: !sandboxAvailable() }, async t => {
  const f = await startFixture(t);
  let observe;
  const effect = new Promise(resolve => { observe = resolve; });
  const destination = await effectDestination(path.join(f.base, 'destination'), { response, observed: observe });
  t.after(() => destination.close());
  const worker = f.controller.status('sesOrigin').worker;
  f.controller.reserveRequest(worker, 'primary');
  const invocation = f.controller.runProcess(worker, { argv: [process.execPath, '--input-type=module', '-e',
    `await fetch(${JSON.stringify(destination.url)}, { method: 'POST', body: JSON.stringify({ operationID: 'controlled-operation' }) });`], network: true, timeoutMs: 5000 });
  await effect;
  if (response === 'hold') await f.controller.pause('sesOrigin', 'The user cancelled after the destination effect.');
  const result = await invocation;
  assert.ok(result.code !== 0 || result.interrupted);
  assert.equal(f.controller.status('sesOrigin').state, 'Paused');
  const action = f.store.list('action')[0];
  assert.equal(action.state, 'unknown');
  assert.equal(action.completionReceived, true);
  assert.equal(destination.receipts().length, 1);
  const dispatches = f.native.sent.length;
  await f.controller.recover();
  assert.equal(destination.receipts().length, 1);
  assert.equal(f.native.sent.length, dispatches);
  assert.equal(f.controller.status('sesOrigin').requests, 1);
  f.user('Resume the goal.');
  await assert.rejects(f.controller.resume('sesOrigin'), /uncertain/);
  const evidence = f.controller.addEvidence('sesOrigin', { kind: 'reconciliation', content: { destination: destination.file, receipts: destination.receipts() } });
  f.controller.reconcileOutcome('sesOrigin', { actionID: action.id, outcome: 'effect', evidenceIDs: [evidence.id] });
  await f.controller.resume('sesOrigin');
  assert.equal(f.controller.status('sesOrigin').worker, worker);
  assert.equal(destination.receipts().length, 1);
  assert.equal(f.store.get('action', action.id).observedOutcome, 'effect');
});
